/** The internal model schema as markdown, generated from `modelSchema` with every field expanded where it stands. */
export function renderModelSchema(): string {
  return [
    '# Internal model schema',
    '',
    ...preamble,
    '',
    renderSchema(modelSchema),
    '',
  ].join('\n');
}

/**
 * One schema's fields as markdown. A check it has no words for is omitted,
 * and a field carrying the model's character rule prints as `text`.
 */
export function renderSchema(schema: Schema): string {
  return expand(schema, '').join('\n');
}

function expand(schema: Schema, indent: string): string[] {
  const def = schema.def;
  if (def.type === 'optional' && def.innerType) {
    return expand(def.innerType, indent);
  }
  if (def.shape) {
    return Object.entries(def.shape).flatMap(([name, field]) =>
      fieldLines(name, field, indent),
    );
  }
  if (def.element) {
    return expand(def.element, indent);
  }
  const discriminator = def.discriminator;
  if (def.options && discriminator !== undefined) {
    return def.options.flatMap((option) =>
      variant(option, discriminator, indent),
    );
  }
  if (def.options?.every((option) => option.def.shape !== undefined)) {
    return holdingVariants(def.options, indent);
  }
  return [];
}

function holdingVariants(options: readonly Schema[], indent: string): string[] {
  const keysOf = (option: Schema) => Object.keys(option.def.shape ?? {});
  const shared = keysOf(options[0]).filter((key) =>
    options.every((option) => keysOf(option).includes(key)),
  );
  return options.flatMap((option) => {
    const own = keysOf(option).filter((key) => !shared.includes(key));
    return [
      `${indent}- when it holds ${listed(own.map((key) => `\`${key}\``))}`,
      ...Object.entries({ ...option.def.shape }).flatMap(([name, field]) =>
        fieldLines(name, field, `${indent}  `),
      ),
    ];
  });
}

function fieldLines(name: string, schema: Schema, indent: string): string[] {
  return [
    `${indent}- \`${name}\`: ${summary(schema)}`,
    ...expand(schema, `${indent}  `),
  ];
}

function variant(
  option: Schema,
  discriminator: string,
  indent: string,
): string[] {
  const shape = { ...option.def.shape };
  return [
    `${indent}- when \`${discriminator}\` is ${summary(shape[discriminator])}`,
    ...Object.entries(shape)
      .filter(([name]) => name !== discriminator)
      .flatMap(([name, field]) => fieldLines(name, field, `${indent}  `)),
  ];
}

function summary(schema: Schema): string {
  const def = schema.def;
  const brand = brands.find(([branded]) => branded === schema);
  if (brand) {
    return `${brand[1]} (${scalar(def)})`;
  }
  if (def.type === 'optional' && def.innerType) {
    return `optional, ${summary(def.innerType)}`;
  }
  if (def.shape) {
    return 'object';
  }
  if (def.element) {
    return `list of ${atLeast(def)}${summary(def.element)}`;
  }
  if (def.options) {
    const total = `one of ${String(def.options.length)}`;
    return def.discriminator === undefined
      ? total
      : `${total}, told apart by \`${def.discriminator}\``;
  }
  if (def.entries) {
    return `one of ${Object.values(def.entries)
      .map((value) => `\`${value}\``)
      .join(', ')}`;
  }
  if (def.values) {
    return def.values.map((value) => `\`${value}\``).join(' or ');
  }
  return scalar(def);
}

function listed(names: readonly string[]): string {
  return names.length < 2
    ? names.join('')
    : `${names.slice(0, -1).join(', ')} and ${names.at(-1) ?? ''}`;
}

function atLeast(def: SchemaDef): string {
  const least = (def.checks ?? []).find(
    (check) => check._zod.def.check === 'min_length',
  )?._zod.def.minimum;
  return least === undefined ? '' : `at least ${String(least)} `;
}

function scalar(def: SchemaDef): string {
  const checks = def.checks ?? [];
  const bounds = checks.flatMap((check) => bound(check._zod.def));
  return [kind(def, checks), ...bounds].join(', ');
}

function kind(def: SchemaDef, checks: readonly Check[]): string {
  if (checks.some((check) => check._zod.def.fn === acceptsEveryCharacter)) {
    return 'text';
  }
  return def.format === 'safeint' ? 'integer' : def.type;
}

function bound(check: CheckDef): string[] {
  if (check.check === 'min_length') {
    return characters('at least', check.minimum);
  }
  if (check.check === 'max_length') {
    return characters('at most', check.maximum);
  }
  if (check.check === 'greater_than') {
    return limit(check.value, (amount) =>
      check.inclusive === true ? `${amount} or more` : `greater than ${amount}`,
    );
  }
  if (check.check === 'less_than') {
    return limit(check.value, (amount) =>
      check.inclusive === true ? `${amount} or less` : `less than ${amount}`,
    );
  }
  return [];
}

function characters(wording: string, count: number | undefined): string[] {
  return count === undefined
    ? []
    : [`${wording} ${String(count)} character${count === 1 ? '' : 's'}`];
}

function limit(
  value: number | undefined,
  phrase: (amount: string) => string,
): string[] {
  return value === undefined ? [] : [phrase(String(value))];
}
